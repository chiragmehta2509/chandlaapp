document.addEventListener('DOMContentLoaded', function() {
    const navLinks = document.querySelectorAll('#toc-nav a');
    const sections = Array.from(navLinks).map(link => document.querySelector(link.getAttribute('href')));
    
    // Smooth scrolling
    navLinks.forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            const targetId = link.getAttribute('href');
            const targetSection = document.querySelector(targetId);
            if(targetSection) {
                window.scrollTo({
                    top: targetSection.offsetTop - 100,
                    behavior: 'smooth'
                });
            }
        });
    });

    // Intersection Observer
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const id = entry.target.getAttribute('id');
                navLinks.forEach(link => {
                    if(link.getAttribute('href') === `#${id}`) {
                        link.classList.add('border-rose-500', 'text-rose-600', 'dark:text-rose-400', 'bg-slate-50', 'dark:bg-white/5');
                        link.classList.remove('border-transparent', 'text-slate-600', 'dark:text-slate-400');
                    } else {
                        link.classList.remove('border-rose-500', 'text-rose-600', 'dark:text-rose-400', 'bg-slate-50', 'dark:bg-white/5');
                        link.classList.add('border-transparent', 'text-slate-600', 'dark:text-slate-400');
                    }
                });
            }
        });
    }, { rootMargin: '-20% 0px -70% 0px' });

    sections.forEach(section => {
        if(section) observer.observe(section);
    });
});
